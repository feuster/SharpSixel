namespace SharpSixel.Ui;

/// <summary>Horizontal alignment of the text in the cells of a <see cref="TableColumn"/>.</summary>
public enum TableAlignment
{
    /// <summary>Text starts at the left edge of the cell.</summary>
    Left,

    /// <summary>Text ends at the right edge of the cell (for numbers).</summary>
    Right,

    /// <summary>Text is centered in the cell.</summary>
    Center,
}
